// Generates pre-computed analyses for the four landing-page example chips.
// Output is written to client/src/data/preloadedExamples.ts so that clicking
// an example renders instantly with no API call.
//
// Re-run after any meaningful change to the prompt schema in api/analyze.ts:
//   node scripts/generate-preloaded-examples.mjs
//
// Reads OPENAI_API_KEY from syntaxis/.env. Cost is roughly $0.10–$0.20 per run.

import OpenAI from 'openai';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SYNTAXIS_ROOT = path.resolve(__dirname, '..');

// Load OPENAI_API_KEY from syntaxis/.env (no dotenv dep — keep it dep-free).
const envPath = path.join(SYNTAXIS_ROOT, '.env');
if (fs.existsSync(envPath)) {
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!process.env[key]) process.env[key] = value;
  }
}

if (!process.env.OPENAI_API_KEY) {
  console.error('OPENAI_API_KEY not set (looked in env and syntaxis/.env)');
  process.exit(1);
}

// Extract SYSTEM_PROMPT from api/analyze.ts so the script always matches the
// current production prompt (no duplicated source of truth).
const analyzePath = path.join(SYNTAXIS_ROOT, 'api', 'analyze.ts');
const analyzeSrc = fs.readFileSync(analyzePath, 'utf8');
const promptMatch = analyzeSrc.match(/const SYSTEM_PROMPT = `([\s\S]*?)`;/);
if (!promptMatch) {
  console.error('Could not extract SYSTEM_PROMPT from', analyzePath);
  process.exit(1);
}
const SYSTEM_PROMPT = promptMatch[1];

// Must match the example chips in client/src/components/InputPanel.tsx exactly.
const EXAMPLES = [
  'Gallia est omnis divisa in partes tres',
  'Arma virumque cano, Troiae qui primus ab oris',
  'Quo usque tandem abutere, Catilina, patientia nostra?',
  'Dum Romae consulitur, Saguntum expugnatur',
];

const client = new OpenAI({ apiKey: process.env.OPENAI_API_KEY, timeout: 60_000 });
const results = {};

for (const sentence of EXAMPLES) {
  process.stdout.write(`Analyzing "${sentence}"… `);
  const t0 = Date.now();
  const completion = await client.chat.completions.create({
    model: 'gpt-4o',
    temperature: 0,
    response_format: { type: 'json_object' },
    messages: [
      { role: 'system', content: SYSTEM_PROMPT },
      { role: 'user', content: sentence },
    ],
  });
  const raw = completion.choices[0]?.message?.content;
  if (!raw) throw new Error(`Empty response for: ${sentence}`);
  results[sentence] = JSON.parse(raw);
  console.log(`done in ${Date.now() - t0}ms (${completion.usage?.completion_tokens} tokens)`);
}

const outPath = path.join(SYNTAXIS_ROOT, 'client', 'src', 'data', 'preloadedExamples.ts');
fs.mkdirSync(path.dirname(outPath), { recursive: true });

const fileBody = `// AUTO-GENERATED by scripts/generate-preloaded-examples.mjs.
// Do not edit by hand. Re-run the script after any meaningful prompt change
// in api/analyze.ts so these analyses stay aligned with live LLM output.

import type { AnalysisResult } from '../components/SentenceAnalysis';

export const PRELOADED_EXAMPLES: Record<string, AnalysisResult> = ${JSON.stringify(results, null, 2)};

export function getPreloadedExample(sentence: string): AnalysisResult | undefined {
  return PRELOADED_EXAMPLES[sentence.trim()];
}
`;

fs.writeFileSync(outPath, fileBody, 'utf8');
console.log('Wrote', path.relative(SYNTAXIS_ROOT, outPath));
